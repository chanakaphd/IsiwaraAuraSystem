/**
 * Custom Notification Toast Engine
 * @param {string} title - Header text for message
 * @param {string} message - Body text detail
 */
function triggerCustomSwalNotification(title, message) {
    const titleNode = document.getElementById('swal-injected-title');
    const msgNode = document.getElementById('swal-injected-msg');
    const containerNode = document.getElementById('custom-swal-container');
    
    if (titleNode) titleNode.innerText = title;
    if (msgNode) msgNode.innerText = message;
    if (containerNode) containerNode.classList.add('show');
}

/**
 * Dismisses the notification box overlay safely
 */
function dismissCustomSwalPopup() {
    const containerNode = document.getElementById('custom-swal-container');
    if (containerNode) containerNode.classList.remove('show');
}

/**
 * Native Bootstrap 5 Safe Modal Show Handler
 * @param {string} modalElementId - Target DOM Element ID
 */
function safeOpenModal(modalElementId) {
    const targetElement = document.getElementById(modalElementId);
    if (!targetElement) return;
    try {
        const modalInstance = new bootstrap.Modal(targetElement);
        modalInstance.show();
    } catch (err) {
        targetElement.style.display = "block";
        targetElement.classList.add("show");
    }
}

/**
 * Native Bootstrap 5 Safe Modal Hide Handler
 * @param {string} modalElementId - Target DOM Element ID
 */
function safeCloseModal(modalElementId) {
    const targetElement = document.getElementById(modalElementId);
    if (!targetElement) return;
    try {
        const activeInstance = bootstrap.Modal.getInstance(targetElement);
        if (activeInstance) activeInstance.hide();
    } catch (e) {
        console.warn("Native modal instance lookup exception. Running manual DOM patch layers.");
    }
    
    targetElement.style.display = "none";
    targetElement.classList.remove("show");
    
    const lingeringBackdrop = document.querySelector('.modal-backdrop');
    if (lingeringBackdrop) lingeringBackdrop.remove();
}

/**
 * Formats seconds integers into standard running clock strings MM:SS
 * @param {number} totalSeconds 
 * @returns {string} Formatted chronological time text
 */
function formatSecondsToMinutesString(totalSeconds) {
    const minutesCalculated = Math.floor(totalSeconds / 60);
    const secondsCalculated = totalSeconds % 60;
    return `${minutesCalculated.toString().padStart(2, '0')}:${secondsCalculated.toString().padStart(2, '0')}`;
}

/**
 * Generates an audible completion beep alert using browser audio synthesis hardware frequencies
 */
function triggerNativeAudioHardwareBeep() {
    try {
        const AudioContextClass = window.AudioContext || window.webkitAudioContext;
        const audioCtxInstance = new AudioContextClass();
        const oscillatorNode = audioCtxInstance.createOscillator();
        const systemGainNode = audioCtxInstance.createGain();
        
        oscillatorNode.connect(systemGainNode);
        systemGainNode.connect(audioCtxInstance.destination);
        
        oscillatorNode.type = 'sine';
        oscillatorNode.frequency.value = 880; // High A5 Pitch Frequency Tone
        systemGainNode.gain.setValueAtTime(0.4, audioCtxInstance.currentTime);
        
        oscillatorNode.start();
        oscillatorNode.stop(audioCtxInstance.currentTime + 0.45); // 450 Milliseconds signal duration burst
    } catch (err) {
        console.warn("Hardware audio synthesis execution blocked by browser permissions context security flags.");
    }
}

